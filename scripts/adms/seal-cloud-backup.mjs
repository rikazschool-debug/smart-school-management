// Seal all backup data and diagnostics. Only ciphertext and a non-sensitive proof leave the runner.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
const project='czoaudsfbinpkwqsmhrd';
const key=Buffer.from(process.env.RK_ADMS_TEST_BACKUP_KEY_20261115??'','base64');
delete process.env.RK_ADMS_TEST_BACKUP_KEY_20261115;
delete process.env.RK_ADMS_TEST_BACKUP_INPUT_20261115;
if(key.length!==32)throw Error('A dedicated backup encryption key is required');
const root=path.join(process.env.RUNNER_TEMP,'rikaz-adms-cloud-backup');
const privateDir=path.join(root,'private');fs.mkdirSync(privateDir,{recursive:true,mode:0o700});
const archive=path.join(root,'backup.private.tgz');
const tar=spawnSync('tar',['-czf',archive,'-C',privateDir,'.'],{stdio:['ignore','ignore','pipe']});
if(tar.status!==0)throw Error('Private archive packaging failed');
let proof={passed:false,project};
const proofPath=path.join(privateDir,'restore-proof.json');
if(fs.existsSync(proofPath))proof=JSON.parse(fs.readFileSync(proofPath,'utf8'));
const plaintext=fs.readFileSync(archive),iv=crypto.randomBytes(12),cipher=crypto.createCipheriv('aes-256-gcm',key,iv);
cipher.setAAD(Buffer.from('rikaz-test-backup:'+project));
const ciphertext=Buffer.concat([cipher.update(plaintext),cipher.final()]);
const sealed=Buffer.concat([Buffer.from('RKBK1'),iv,cipher.getAuthTag(),ciphertext]);
const output=path.resolve('cloud-test-artifacts');fs.mkdirSync(output,{recursive:true,mode:0o700});
fs.writeFileSync(path.join(output,'cloud-test-backup.enc'),sealed,{mode:0o600});
const publicProof={...proof,project,workflowRun:process.env.GITHUB_RUN_ID,runnerCommit:process.env.GITHUB_SHA,encrypted:true,encryption:'AES-256-GCM',encryptedSha256:crypto.createHash('sha256').update(sealed).digest('hex'),productionContacted:false,backupCredentialsInArtifact:false};
delete publicProof.backupPath;delete publicProof.rolesPath;
fs.writeFileSync(path.join(output,'proof.json'),JSON.stringify(publicProof,null,2));
key.fill(0);plaintext.fill(0);fs.unlinkSync(archive);
console.log(JSON.stringify({sealed:true,project,restorePassed:publicProof.passed===true,migrationRehearsalPassed:publicProof.migrationRehearsalPassed===true,productionContacted:false}));
