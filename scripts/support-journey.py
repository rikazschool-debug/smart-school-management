# Full support journey in the browser with separate accounts (two branches + another org + platform admin) on the sbx- fixture.
# Needs: NODE_PATH=node_modules bun scripts/support-browser-fixture.ts setup   (teardown after)
import asyncio, json, re, time
from playwright.async_api import async_playwright
F = json.load(open("/tmp/browser/sup/fixture.json")); B = "http://localhost:8080"; D = "/tmp/browser/sup/"
res = []; TITLE = f"تعذر رفع الدرجات {int(time.time())}"; BODY = "الوصف الأصلي السري للمشكلة"
def chk(n, c, info=""): res.append(bool(c)); print("PASS" if c else "FAIL", n, "" if c else info, flush=True)
async def login(br, who):
    ctx = await br.new_context(viewport={"width": 1280, "height": 1800}); p = await ctx.new_page()
    await p.goto(B + "/auth"); await p.wait_for_timeout(2500)
    await p.fill("#email", F["users"][who]["email"]); await p.fill("#password", F["pw"]); await p.press("#password", "Enter")
    await p.wait_for_function("location.pathname.startsWith('/app')", timeout=30000); return p
async def go(p, q, wait=3500): await p.goto(B + "/app/support" + q); await p.wait_for_timeout(wait)
async def dialog(p, text=None):
    dlg = p.get_by_role("alertdialog")
    await dlg.wait_for(timeout=8000)
    if text is not None: await dlg.locator("input").fill(text)
    await dlg.get_by_role("button", name="تأكيد").click(); await p.wait_for_timeout(2500)
async def pick(p, group, name):
    g = p.get_by_role("group", name=group)
    await g.get_by_placeholder("اكتب أول أحرف الاسم").fill(name.split()[0]); await p.wait_for_timeout(1500)
    await g.get_by_text(name, exact=True).click()
async def body(p): return await p.locator("main").inner_text()
async def main():
    async with async_playwright() as pw:
        br = await pw.chromium.launch(headless=True)
        P = {w: await login(br, w) for w in ["tch", "pr1", "tchB", "tch2", "owner", "pr2", "pa", "owner2"]}
        t = P["tch"]
        await go(t, "?tab=mine"); await t.get_by_role("button", name="تذكرة جديدة").click()
        await t.fill("#sp-title", TITLE); await t.fill("#sp-body", BODY); await t.get_by_role("button", name="إرسال التذكرة").click()
        await t.wait_for_function("location.search.includes('t=')", timeout=15000); T = re.search(r"t=([0-9a-f-]{36})", t.url).group(1)
        await t.wait_for_timeout(2500); await t.set_input_files("input[type=file]", D + "evidence.png"); await t.wait_for_timeout(5000)
        chk("J1 teacher creates a ticket and attaches a file", "evidence.png" in await body(t), "")
        await t.screenshot(path=D + "j1.png")
        p1 = P["pr1"]; await go(p1, f"?t={T}")
        await pick(p1, "مسؤول المعالجة", "معلم فرع ب"); await p1.get_by_role("button", name="إسناد", exact=True).click(); await p1.wait_for_timeout(3000)
        await p1.get_by_label("نوع الملاحظة").select_option("private"); await p1.wait_for_timeout(500)
        await p1.get_by_label("مستلم الملاحظة").select_option(label="معلم فرع ب"); await p1.get_by_label("نص الملاحظة").fill("سري-ج للمعلم فقط")
        await p1.get_by_role("button", name="حفظ الملاحظة").click(); await p1.wait_for_timeout(3000)
        b = P["tchB"]; await go(b, "?tab=assigned")
        chk("J2 principal assigns to a teacher in another branch; it appears in his «المسندة إليّ»", TITLE in await body(b), "")
        await go(b, f"?t={T}"); bb = await body(b)
        chk("J3 assignee opens it and sees the private note addressed to him", TITLE in bb and "سري-ج" in bb, "")
        await go(p1, f"?t={T}"); await pick(p1, "مسؤول المعالجة", "معلمة مساندة"); await p1.get_by_role("button", name="إسناد", exact=True).click(); await p1.wait_for_timeout(3000)
        await go(b, f"?t={T}"); bb = await body(b)
        c2 = P["tch2"]; await go(c2, f"?t={T}"); cc = await body(c2)
        chk("J4 after reassignment the previous assignee loses access by direct link; the new one opens it without the old private note", TITLE not in bb and TITLE in cc and "سري-ج" not in cc, (bb[:200], cc[:200]))
        await go(p1, f"?t={T}"); await pick(p1, "من تُطلب إفادته", "معلم فرع ب")
        await p1.get_by_label("السؤال أو الجزء المطلوب الإفادة عنه").fill("هل ظهرت المشكلة نفسها في فرع ب؟"); await p1.get_by_role("button", name="إرسال طلب الإفادة").click(); await p1.wait_for_timeout(3000)
        await p1.get_by_label("نوع الملاحظة").select_option("team"); await p1.get_by_label("نص الملاحظة").fill("ملاحظة-فريق-ج"); await p1.get_by_role("button", name="حفظ الملاحظة").click(); await p1.wait_for_timeout(2500)
        await go(b, "?tab=info"); ib = await body(b)
        chk("J5 cross-branch info request: the teacher sees only the question, not the title/description", "فرع ب؟" in ib and BODY not in ib, ib[:300])
        await b.get_by_label("إفادتك").first.fill("نعم ظهرت يوم الأحد"); await b.get_by_role("button", name="إرسال الإفادة").first.click(); await b.wait_for_timeout(3000)
        await go(p1, f"?t={T}")
        chk("J6 handler sees the answer", "نعم ظهرت يوم الأحد" in await body(p1), "")
        await go(t, f"?t={T}"); tb = await body(t)
        chk("J7 requester sees none of the internal notes/questions/answers", TITLE in tb and not any(x in tb for x in ["سري-ج", "ملاحظة-فريق-ج", "فرع ب؟", "نعم ظهرت"]), "")
        o = P["owner"]; await go(o, f"?t={T}")
        await o.locator("#sp-branch").select_option(label="فرع ب التجريبي"); await o.get_by_label("سبب التحويل").fill("الاختصاص في فرع ب"); await o.get_by_role("button", name="تحويل", exact=True).click()
        try: await dialog(o)
        except Exception: await o.wait_for_timeout(2000)
        await go(p1, f"?t={T}"); p1b = await body(p1); p2 = P["pr2"]; await go(p2, f"?t={T}"); p2b = await body(p2)
        chk("J8 owner transfers to branch B: branch A principal loses access, branch B principal opens it", TITLE not in p1b and TITLE in p2b, (p1b[:150], p2b[:150]))
        await go(o, f"?t={T}"); await o.get_by_role("button", name="تصعيد إلى دعم المنصة").click()
        await o.get_by_label("ما تريد مشاركته مع المنصة").fill("مقتطف مختار للمنصة فقط"); await o.get_by_role("button", name="إرسال للمنصة").click(); await o.wait_for_timeout(3500)
        pa = P["pa"]; await go(pa, "?tab=manage"); pab = await body(pa)
        await pa.get_by_text(TITLE).first.click(); await pa.wait_for_timeout(3500); pd = await body(pa)
        chk("J9 platform admin sees the escalated ticket with only the chosen excerpt", TITLE in pab and "مقتطف مختار" in pd and BODY not in pd and "سري-ج" not in pd, pd[:300])
        await go(pa, f"?t={T}"); pin = await body(pa)
        await go(P["owner2"], f"?t={T}"); xo = await body(P["owner2"])
        chk("J10 direct link to the school ticket refused for platform admin and another org's owner", BODY not in pin and TITLE not in xo, (pin[:150], xo[:150]))
        await go(p2, f"?t={T}")
        await p2.locator("#sp-reply").fill("تم إصلاح رفع الدرجات"); await p2.get_by_role("button", name="إرسال الرد").click(); await p2.wait_for_timeout(2500)
        await p2.get_by_role("button", name="حل التذكرة").click(); await dialog(p2, "تحديث صلاحية الرفع")
        await go(t, f"?t={T}"); await t.get_by_role("button", name="تأكيد الحل").click(); await dialog(t, "5")
        await go(t, f"?t={T}"); tb = await body(t)
        chk("J11 resolved by branch B principal; requester sees the reply, rates and closes", "تم إصلاح رفع الدرجات" in tb and "مغلقة" in tb, tb[:400])
        await t.get_by_role("button", name="إعادة فتح").click(); await dialog(t, "عادت المشكلة اليوم")
        await go(t, f"?t={T}"); tb = await body(t)
        chk("J12 requester reopens within the window; ticket back in progress", "قيد المعالجة" in tb, tb[:300])
        await t.screenshot(path=D + "j12.png")
        await br.close()
    print(f"{sum(res)}/{len(res)} passed")
asyncio.run(main())
